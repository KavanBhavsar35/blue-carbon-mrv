
from marshmallow import Schema, fields

class UserSchema(Schema):
    id = fields.Str(required=True)
    name = fields.Str()
    email = fields.Email(required=True)
    email_verified = fields.Bool()
    image = fields.Str()
    created_at = fields.DateTime(dump_only=True)
    updated_at = fields.DateTime(dump_only=True)

class UserProfileSchema(Schema):
    id = fields.Str(required=True)
    user_id = fields.Str(required=True)
    role = fields.Str()
    wallet_address = fields.Str()
    organization = fields.Str()
    country = fields.Str()
    phone_number = fields.Str()
    bio = fields.Str()
    total_credits_earned = fields.Float()
    total_credits_sold = fields.Float()
    total_credits_bought = fields.Float()
    created_at = fields.DateTime(dump_only=True)
    updated_at = fields.DateTime(dump_only=True)

class VerificationSchema(Schema):
    id = fields.Str(required=True)
    identifier = fields.Str(required=True)
    value = fields.Str(required=True)
    expires_at = fields.DateTime(required=True)
    created_at = fields.DateTime(dump_only=True)
    updated_at = fields.DateTime(dump_only=True)

class ProjectUserSchema(Schema):
    id = fields.Str(required=True)
    project_id = fields.Str(required=True)
    user_id = fields.Str(required=True)
    role = fields.Str()
    joined_at = fields.DateTime(dump_only=True)

class ProjectSchema(Schema):
    id = fields.Str(required=True)
    organization_name = fields.Str(required=True)
    organization_type = fields.Str(required=True)
    registration_number = fields.Str()
    contact_person = fields.Str(required=True)
    email = fields.Email(required=True)
    phone = fields.Str(required=True)
    project_name = fields.Str(required=True)
    project_description = fields.Str(required=True)
    project_type = fields.Str(required=True)
    state = fields.Str(required=True)
    district = fields.Str(required=True)
    village = fields.Str(required=True)
    coordinates = fields.Raw()
    total_area = fields.Float(required=True)
    estimated_credits_per_year = fields.Float(required=True)
    total_credits_generated = fields.Float()
    has_legal_permits = fields.Bool()
    has_survey_report = fields.Bool()
    has_environmental_clearance = fields.Bool()
    contract_address = fields.Str()
    token_id = fields.Str()
    status = fields.Str()
    created_at = fields.DateTime(dump_only=True)
    updated_at = fields.DateTime(dump_only=True)

class CarbonCreditSchema(Schema):
    id = fields.Str(required=True)
    project_id = fields.Str(required=True)
    amount = fields.Float(required=True)
    vintage = fields.Int(required=True)
    status = fields.Str()
    blockchain_tx_hash = fields.Str()
    minted_at = fields.DateTime()
    burned_at = fields.DateTime()
    certification_body = fields.Str()
    certification_id = fields.Str()
    created_at = fields.DateTime(dump_only=True)
    updated_at = fields.DateTime(dump_only=True)

class TransactionSchema(Schema):
    id = fields.Str(required=True)
    transaction_type = fields.Str(required=True)
    from_user_id = fields.Str()
    to_user_id = fields.Str()
    project_id = fields.Str()
    credit_id = fields.Str()
    amount = fields.Float(required=True)
    price_per_credit = fields.Float()
    total_price = fields.Float()
    currency = fields.Str()
    tx_hash = fields.Str()
    block_number = fields.Int()
    gas_used = fields.Float()
    status = fields.Str()
    meta_data = fields.Raw()
    created_at = fields.DateTime(dump_only=True)
    updated_at = fields.DateTime(dump_only=True)